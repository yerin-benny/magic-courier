export const countries: Country[] = groups.flatMap(([continent, rows]) =>
  rows.split(';').map((row) => {
    const [id, name, capital, lat, lon] = row.split('|');
    return {
      id,
      name,
      capital,
      continent,
      lat: Number(lat),
      lon: Number(lon),
      intro: introductions[id],
    };
  }),
);
export function country(id: string) {
  return countries.find((c) => c.id === id)!;
}
